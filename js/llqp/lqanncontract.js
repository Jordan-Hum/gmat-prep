  <tr><td><b>Locked-in</b> pension money (LIRA, LIF)</td><td>Must buy a <b>life</b> annuity (not term-certain). If the annuitant has a spouse, it must be a <b>joint and survivor</b> annuity paying the survivor at least <b>60%</b>, unless the spouse signs a waiver</td></tr>
