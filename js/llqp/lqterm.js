<h3>4. Advantages and disadvantages of term</h3>
<table>
  <tr><th>Advantages</th><th>Disadvantages</th></tr>
  <tr><td>
    <ul>
      <li>Lowest initial cost for large coverage</li>
      <li>Simple and easy to compare</li>
      <li>Renewable and convertible options protect insurability</li>
      <li>Matches temporary needs</li>
    </ul>
  </td><td>
